#pragma once
#ifndef VOTCA_XTP_DIABATWRITER_H
#define VOTCA_XTP_DIABATWRITER_H

// Standard includes
#include <ostream>
#include <string>

// Local VOTCA includes
#include "votca/xtp/orbitals.h"
#include "votca/xtp/qmstate.h"

namespace votca {
namespace xtp {

/**
 * \brief Writes BSE excitations in the plain-text electronic-state format
 * read by Diabat 2.0 (https://github.com/laughtale-lab/diabat) as `statefile`.
 *
 * The file is meant to be used together with an fchk written by
 * GaussianWriter with UseBSEOrbitals(true) from the same Orbitals object
 * (Diabat `mofile`): amplitudes refer to those MOs by absolute 1-based index.
 *
 * Conventions (closed-shell, restricted, as in Diabat's own TDDFT files):
 *  - only alpha amplitudes are listed; spin-adapted singlet/triplet vectors
 *    are scaled by 1/sqrt(2), so that sum x^2 - sum y^2 = 1/2,
 *  - "i --> a" lines carry the resonant part X, "i <-- a" lines the
 *    anti-resonant part Y (full BSE only); method label is TDA or TDDFT,
 *  - energies: reference = DFT total energy, state = reference + Omega_BSE.
 *
 * Diabat identifies the file type by its first line, so that line has to be
 * Diabat's own header string verbatim.
 */
class DiabatWriter {
 public:
  /// Write the first `nstates` states of `type` (Singlet or Triplet);
  /// nstates <= 0 writes all available states.
  void WriteFile(const std::string& filename, const Orbitals& orbitals,
                 QMStateType type, Index nstates = -1) const;

  void Write(std::ostream& out, const Orbitals& orbitals, QMStateType type,
             Index nstates = -1) const;

  /// First line Diabat 2.0 uses to recognise its native state format.
  static constexpr const char* FormatIdentifier =
      "# Information of wavefunction generated by Diabat 2.0";
};

}  // namespace xtp
}  // namespace votca

#endif  // VOTCA_XTP_DIABATWRITER_H
